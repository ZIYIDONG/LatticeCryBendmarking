#pragma once
/**
 * @file ntru_trapgen.h
 * @brief NTRU Trapdoor Generation (TrapGen) — 完整主流程
 *
 * Implements the full NTRU TrapGen algorithm from the IBAGS paper:
 *   1. Sample f, g (short polynomials via discrete Gaussian)
 *   2. Check f is invertible in R_p = Z_q[x]/(x^n+1); re-sample if not
 *   3. Compute f_inv, then h = g * f_inv mod (q, x^n+1)
 *   4. (Optional) Check h is invertible; precompute h_inv if needed
 *   5. Solve NTRU equation f*G - g*F = q (mod x^n+1) to get F, G
 *   6. Assemble TrapdoorBasis B = [[c(f), c(g)], [c(F), c(G)]]
 *   7. Output PublicTrapdoorParams { h, params } and
 *      MasterTrapdoorSecret { f, g, F, G, B, h_inv }
 *
 * Reference:
 *   - Falcon specification §3.1 (f, g sampling and invertibility)
 *   - NTRU key generation (IEEE P1363.1)
 *   - Ducas–Lyubashevsky–Prest (DLP) trapdoor construction
 *
 * Production notes:
 *   - Current NTRU equation solver is a [STUB]: in PoC, stores F, G as zeros
 *     and marks the solver as NOT_FOR_PRODUCTION.
 *   - Production must integrate a full NTRU equation solver (e.g., using
 *     Babai nearest plane on NTRU lattice, or the Falcon-compatible solver).
 *   - Sample-until-invertible loop has configurable max_attempts.
 *   - All secret polynomials are zeroed on destruction (SecretPoly / Poly).
 */

#include "params.h"
#include "poly.h"
#include "secure_memory.h"
#include "csprng.h"
#include "errors.h"

#include <cstddef>
#include <cstdint>
